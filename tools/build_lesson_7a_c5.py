def slide(kind, title, body=None, problem=None, solution=None, notes=None, book_ref=None):
    s = {"kind": kind, "title": title}
    if body is not None:
        s["body"] = body
    if problem is not None:
        s["problem"] = problem
    if solution is not None:
        s["solution"] = solution
    if notes is not None:
        s["notes"] = notes
    if book_ref is not None:
        s["bookRef"] = book_ref
    return s

def lesson(pid, title, minutes, objectives, slides, summary, checks):
    return {
        "pointId": pid,
        "title": title,
        "durationMinutes": minutes,
        "objectives": objectives,
        "slides": slides,
        "summary": summary,
        "checkQuestions": [{"question": q, "answer": a} for q, a in checks],
    }

